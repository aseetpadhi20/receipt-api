CREATE TABLE receipt (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY,
    original_filename VARCHAR(255)             NOT NULL,
    content_type      VARCHAR(100)             NOT NULL,
    size_bytes        BIGINT                   NOT NULL,
    storage_backend   VARCHAR(20)              NOT NULL,
    storage_key       VARCHAR(500)             NOT NULL,
    raw_ocr_text      TEXT,
    uploaded_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    processed_at      TIMESTAMP WITH TIME ZONE,

    CONSTRAINT pk_receipt              PRIMARY KEY (id),
    CONSTRAINT uq_receipt_storage_key  UNIQUE (storage_backend, storage_key),
    CONSTRAINT ck_receipt_size         CHECK (size_bytes > 0),
    CONSTRAINT ck_receipt_backend      CHECK (storage_backend IN ('local', 'aws', 'azure')),
    CONSTRAINT ck_receipt_content_type CHECK (content_type IN ('image/jpeg', 'image/png', 'application/pdf', 'text/plain')),
    CONSTRAINT ck_receipt_processed    CHECK (processed_at IS NULL OR raw_ocr_text IS NOT NULL)
);

CREATE TABLE expense_transaction (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY,
    receipt_id       BIGINT                   NOT NULL,
    merchant         VARCHAR(255),
    transaction_date DATE,
    currency         CHAR(3),
    grand_total      DECIMAL(12, 2),
    itemize_status   VARCHAR(20)              NOT NULL,
    itemize_note     VARCHAR(500),
    version          BIGINT                   NOT NULL DEFAULT 0,
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at       TIMESTAMP WITH TIME ZONE NOT NULL,

    CONSTRAINT pk_expense_transaction PRIMARY KEY (id),
    CONSTRAINT fk_transaction_receipt FOREIGN KEY (receipt_id) REFERENCES receipt (id) ON DELETE CASCADE,
    CONSTRAINT uq_transaction_receipt UNIQUE (receipt_id),
    CONSTRAINT ck_transaction_total   CHECK (grand_total IS NULL OR grand_total >= 0),
    CONSTRAINT ck_transaction_status  CHECK (itemize_status IN ('COMPLETE', 'NEEDS_REVIEW', 'FAILED')),
    CONSTRAINT ck_transaction_failed  CHECK (grand_total IS NOT NULL OR itemize_status = 'FAILED')
);

CREATE TABLE transaction_tax (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    transaction_id BIGINT         NOT NULL,
    name           VARCHAR(20)    NOT NULL,
    rate           DECIMAL(7, 6)  NOT NULL,
    amount         DECIMAL(12, 2) NOT NULL,
    inclusive      BOOLEAN        NOT NULL,
    jurisdiction   VARCHAR(50),

    CONSTRAINT pk_transaction_tax     PRIMARY KEY (id),
    CONSTRAINT fk_tax_transaction     FOREIGN KEY (transaction_id) REFERENCES expense_transaction (id) ON DELETE CASCADE,
    CONSTRAINT ck_tax_rate            CHECK (rate >= 0 AND rate <= 1),
    CONSTRAINT ck_tax_amount          CHECK (amount >= 0)
);

CREATE INDEX ix_tax_transaction ON transaction_tax (transaction_id);

CREATE TABLE transaction_item (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    transaction_id BIGINT         NOT NULL,
    position       INT            NOT NULL,
    description    VARCHAR(255)   NOT NULL,
    amount         DECIMAL(12, 2) NOT NULL,
    quantity       DECIMAL(10, 3),
    tax_amount     DECIMAL(12, 2),
    source         VARCHAR(10)    NOT NULL,

    CONSTRAINT pk_transaction_item    PRIMARY KEY (id),
    CONSTRAINT fk_item_transaction    FOREIGN KEY (transaction_id) REFERENCES expense_transaction (id) ON DELETE CASCADE,
    CONSTRAINT ck_item_amount         CHECK (amount >= 0),
    CONSTRAINT ck_item_quantity       CHECK (quantity IS NULL OR quantity > 0),
    CONSTRAINT ck_item_tax_amount     CHECK (tax_amount IS NULL OR tax_amount >= 0),
    CONSTRAINT ck_item_source         CHECK (source IN ('AUTO', 'USER'))
);

CREATE INDEX ix_item_transaction ON transaction_item (transaction_id);
